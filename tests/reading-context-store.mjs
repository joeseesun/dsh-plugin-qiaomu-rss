import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
const require=createRequire(process.env.QMR_TEST_DEPENDENCIES);
const {Context}=await import(require.resolve('@deepseek-ai/cordis'));
process.env.DSH_HOME=await mkdtemp(join(tmpdir(),'qrs-annotations-'));
const {default:Service}=await import(process.env.QMR_HOST_MODULE);
let contribution;
const root=new Context();root.reflect.provide('systemPrompt',{context(c){contribution=c;}});root.reflect.provide('tools',{register(){}});
const service=new Service(root);await service.ready;
service.store.putArticle({key:'test',title:'Article',html:'<p>Article text</p>',url:'https://example.org'});
await service.setReadingContext({sessionId:'test-session',key:'test',selection:'Article text'});
assert.match(contribution.text({agent:{session:{id:'test-session'}}}),/Article text/);
assert.equal(contribution.text({agent:{session:{id:'unrelated-session'}}}),'');
assert.equal(contribution.interpolate,false);
await service.store.dispose();
const root2=new Context();root2.reflect.provide('tools',{register(){}});const next=new Service(root2);await next.ready;
assert.match(next.store.data.companionContexts['test-session'].text,/Article text/);
next.store.data.read.test=true;next.store.data.favorites.test={};next.store.data.qiaomuStream.entries=[{key:'test',title:'Article'},{key:'other',title:'Other'}];
assert.equal((await next.listEntries({channel:'qiaomu',filter:'favorites'})).entries.length,1);
await next.store.dispose();console.log('Reading context: active-session scope, persistence, favorites filter passed');
